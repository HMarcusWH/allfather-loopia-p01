<?php

declare(strict_types=1);

namespace Allfather\Loopia\Tests;

use Allfather\Loopia\Core\Digest;
use Allfather\Loopia\Core\FixedClock;
use Allfather\Loopia\Core\Ids;
use Allfather\Loopia\Ingestion\EgressGuard;
use Allfather\Loopia\Ingestion\FetchResponse;
use Allfather\Loopia\Ingestion\FixedHostResolver;
use Allfather\Loopia\Ingestion\FixtureTransport;
use Allfather\Loopia\Provider\FixtureModelTransport;
use Allfather\Loopia\Provider\ModelResponse;
use Allfather\Loopia\Provider\PreparedModelRequest;

/**
 * BF-01 explicit CLI-only offline composition.
 *
 * Reuses the actual EgressGuard/SourcePolicy + FixedClock and native fixture
 * transports. Its ephemeral append-only records are test instrumentation, NOT
 * M05 evidence, persisted owner state, or M10 release records.
 *
 * Deliberately lives under tests/support, not app/: the production autoloader
 * cannot resolve this class and web/scheduler entrypoints never require it.
 */
final class LongitudinalBuildHarness
{
    private const ORIGIN = 'https://bf01.example';
    private const SCOPE = self::ORIGIN . '/pricing';
    public const STATUS = 'SYNTHETIC_ONLY_NOT_AUTHORIZED';
    private const ALLOWED_CASES = ['allowed', 'redirect_refused', 'timeout'];

    /** @var list<array<string, mixed>> */
    private array $candidateRecords = [];

    private function __construct(
        private readonly string $caseId,
        private readonly FixedClock $clock,
        private readonly FixtureTransport $source,
        private readonly FixedHostResolver $resolver,
        private readonly FixtureModelTransport $model,
    ) {
    }

    public static function forCase(string $caseId): self
    {
        if (PHP_SAPI !== 'cli') {
            throw new \DomainException('BF01_HARNESS_NOT_AVAILABLE_OVER_HTTP');
        }
        if (!in_array($caseId, self::ALLOWED_CASES, true)) {
            throw new \DomainException('BF01_HARNESS_UNKNOWN_FIXTURE');
        }
        $responses = [
            self::SCOPE => $caseId === 'redirect_refused'
                ? new FetchResponse(302, 'text/plain', '/outside', '')
                : new FetchResponse(200, 'text/plain', null, 'Synthetic competitor pricing v1'),
            self::ORIGIN . '/outside' => new FetchResponse(200, 'text/plain', null, 'Never requested'),
        ];
        if ($caseId === 'timeout') {
            $responses[self::SCOPE] = new \Allfather\Loopia\Ingestion\TransportTimeout();
        }
        return new self(
            $caseId,
            new FixedClock('2026-10-28T00:00:00.000Z'),
            new FixtureTransport($responses),
            new FixedHostResolver(['bf01.example' => ['93.184.216.34']]),
            new FixtureModelTransport(static fn (PreparedModelRequest $request): ModelResponse
                => new ModelResponse(200, '{"synthetic":true}')),
        );
    }

    /** @return array<string,mixed> raw EgressGuard outcome (no wrapper authorization). */
    public function observe(string $url = self::SCOPE): array
    {
        return EgressGuard::guardedFetch(
            url: $url,
            allowedHosts: ['bf01.example'],
            transport: $this->source,
            resolver: $this->resolver,
            method: 'GET',
            timeoutMs: 1000,
            maxResponseBytes: 1024,
            maxRedirects: 1,
            allowedContentTypes: ['text/plain'],
            allowedOrigin: EgressGuard::effectiveHttpsOrigin(self::SCOPE),
            allowedUrlScope: self::SCOPE,
        );
    }

    /** @return list<string> */
    public function attemptedUrls(): array
    {
        return $this->source->attemptedUrls();
    }

    /** @return list<?string> */
    public function pinnedIps(): array
    {
        return $this->source->pinnedIps();
    }

    /** @return array{is_live:bool,calls:int,authority:string} */
    public function modelPosture(): array
    {
        return ['is_live' => $this->model->isLive(), 'calls' => $this->model->calls, 'authority' => self::STATUS];
    }

    public function now(): string
    {
        return $this->clock->now();
    }

    public function advanceDays(int $days): void
    {
        if ($days <= 0 || $days > 7) {
            throw new \DomainException('BF01_HARNESS_CLOCK_STEP_OUT_OF_SCOPE');
        }
        $this->clock->advanceDays($days);
    }

    /**
     * In-memory disposable candidate record; no SQL, I/O, evidence bytes,
     * model, action or production grant. Only generated by the CLI test case.
     * @return array{record_digest:string,stored:int}
     */
    public function appendCandidate(string $tenantId, string $workspaceId, string $kind, string $basisDigest): array
    {
        if (!Ids::isValid($tenantId) || !Ids::isValid($workspaceId) || $tenantId === $workspaceId) {
            throw new \DomainException('BF01_HARNESS_SCOPE_REFUSED');
        }
        if (!in_array($kind, ['CAPTURE_CANDIDATE','REVIEW_DUE_CANDIDATE'], true)
            || preg_match('/^[a-f0-9]{64}$/D', $basisDigest) !== 1) {
            throw new \DomainException('BF01_HARNESS_UNSUPPORTED_CANDIDATE');
        }
        $record = [
            'tenant_id' => $tenantId, 'workspace_id' => $workspaceId,
            'kind' => $kind, 'basis_digest' => $basisDigest,
            'observed_at' => $this->clock->now(),
            'authority' => self::STATUS,
            'revision' => count($this->candidateRecords) + 1,
        ];
        $record['record_digest'] = Digest::canonicalDigest($record);
        $this->candidateRecords[] = $record;
        return ['record_digest' => $record['record_digest'], 'stored' => count($this->candidateRecords)];
    }

    /** @return list<array<string,mixed>> */
    public function candidateRecords(string $tenantId, string $workspaceId): array
    {
        return array_values(array_filter(
            $this->candidateRecords,
            static fn (array $r): bool => $r['tenant_id'] === $tenantId && $r['workspace_id'] === $workspaceId,
        ));
    }
}
